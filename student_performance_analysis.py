df['schoolsup_numeric'] = df['schoolsup'].map({'yes': 1, 'no': 0})
df['overall_parental_support'] = df['famsup_numeric'] + df['schoolsup_numeric']
df.drop(['famsup_numeric', 'schoolsup_numeric'], axis=1, inplace=True)

# 'goout_study_balance': Ratio of time spent going out to study time

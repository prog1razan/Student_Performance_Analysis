# 'study_success_ratio' (handle potential division by zero for 'failures')
# Adding 1 to failures in the denominator to avoid division by zero and to give higher values for fewer failures
# NOTE: In the current `df`, 'failures' only contains 0s, so this feature will have limited variability.
df['study_success_ratio'] = df.apply(lambda row: row['studytime'] / (row['failures'] + 1) if row['failures'] >= 0 else 0, axis=1)

# 'total_alcohol_consumption': Sum of workday and weekend alcohol consumption
df['total_alcohol_consumption'] = df['Dalc'] + df['Walc']

# 'overall_parental_support': Numeric representation of famsup and schoolsup
